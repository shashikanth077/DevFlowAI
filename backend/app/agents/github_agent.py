"""Agent 9 - GitHub Release Engineer.

Creates a feature branch, commits *only* the reviewed and approved files,
pushes the branch and opens a pull request. It never pushes to the base branch
or to any protected branch, and it never merges.
"""

from __future__ import annotations

import re
from typing import Any

from app.agents.base import BaseAgent
from app.agents.review_agent import diff_hash
from app.core.errors import DevFlowError, GitHubError
from app.services.github_service import is_protected_branch_name


def slugify(text: str, max_length: int = 40) -> str:
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return slug[:max_length].rstrip("-") or "change"


def branch_name_for(title: str, workflow_id: str) -> str:
    return f"devflow/{slugify(title)}-{workflow_id[:8]}"


def _status_icon(status: str) -> str:
    return {"passed": "✅", "failed": "❌", "not_run": "⚠️", "error": "❌"}.get(status, "•")


def build_pr_body(state: dict) -> str:
    req = state.get("requirement_analysis", {})
    tests = state.get("test_results", {})
    review = state.get("review_feedback", {})
    tasks = state.get("development_tasks", [])
    lines = [
        "## Requirement",
        state.get("user_requirement", "").strip(),
        "",
        "## Summary",
        req.get("summary", ""),
        "",
        "## Acceptance criteria",
        *[f"- [ ] {c}" for c in state.get("acceptance_criteria", [])],
        "",
        "## Implementation",
        state.get("architecture_plan", {}).get("approach", ""),
        "",
        "| Task | Agent | Status |",
        "| --- | --- | --- |",
        *[f"| {t['id']}: {t['title']} | {t['assigned_agent']} | {t['status']} |" for t in tasks],
        "",
        "### Files",
        *[f"- `{p}` (new)" for p in state.get("generated_files", [])],
        *[f"- `{p}` (modified)" for p in state.get("modified_files", [])],
        "",
        "## Test results",
        f"{_status_icon(tests.get('status', ''))} **{tests.get('status', 'unknown')}** - {tests.get('summary', '')}",
    ]
    for command in tests.get("commands", []):
        ok = command.get("exit_code") == 0 and not command.get("timed_out")
        lines.append(f"- {'✅' if ok else '❌'} `{command.get('command')}` ({command.get('phase')}, "
                     f"{command.get('component')}, exit {command.get('exit_code')})")
    for note in tests.get("coverage_notes", []):
        lines.append(f"- ⚠️ {note}")
    lines += [
        "",
        "## Code review",
        f"{'✅ Approved' if review.get('approved') else '❌ Not approved'} by `{review.get('reviewer_model', '')}`: "
        f"{review.get('summary', '')}",
    ]
    for issue in (review.get("issues", []) + review.get("automated_findings", []))[:20]:
        lines.append(f"- [{issue.get('severity')}] {issue.get('file') or 'general'}: {issue.get('message')}")
    if req.get("ambiguities"):
        lines += ["", "## Open questions", *[f"- {q}" for q in req["ambiguities"]]]
    lines += [
        "",
        "---",
        f"_Generated by DevFlow AI (workflow `{state.get('workflow_id', '')}`). "
        "Human approval was given before this pull request was opened. It is not merged automatically._",
    ]
    return "\n".join(lines)


class GitHubReleaseAgent(BaseAgent):
    name = "release_engineer"

    def run(self, state: dict) -> dict[str, Any]:
        ws = self.rt.workspace()
        current = diff_hash(ws.diff())
        approved_hash = state.get("approved_diff_hash")
        if not approved_hash or current != approved_hash:
            raise DevFlowError("Workspace changed after code review; refusing to release unreviewed code.")
        approved_files = list(dict.fromkeys(list(state.get("generated_files", [])) + list(state.get("modified_files", []))))
        changed_now = {c["path"] for c in ws.changed_files()}
        unexpected = changed_now - set(approved_files)
        if unexpected:
            self.log(f"Excluding unapproved changes from commit: {sorted(unexpected)}", level="warning")
        approved_files = [p for p in approved_files if p in changed_now]

        base = state["base_branch"]
        full_name = state["repository_full_name"]
        title = state.get("requirement_analysis", {}).get("title") or state["user_requirement"][:60]
        branch = state.get("feature_branch") or branch_name_for(title, state["workflow_id"])
        github = self.rt.github()
        try:
            if branch == base or is_protected_branch_name(branch, self.rt.settings.protected_branch_patterns):
                raise DevFlowError(f"Refusing to push to protected branch '{branch}'")
            if github.branch_exists(full_name, branch):
                branch = f"{branch}-{state['workflow_id'][8:12]}"
                if github.branch_exists(full_name, branch):
                    raise DevFlowError(f"Branch {branch} already exists on GitHub")
            self.log(f"Creating branch {branch} from {base}")
            ws.checkout_new_branch(branch)
            message = f"feat: {title}\n\n{state.get('requirement_analysis', {}).get('summary', '')}\n\n" \
                      f"Generated by DevFlow AI workflow {state['workflow_id']}"
            commit_id = ws.commit(approved_files, message, author_name=self.rt.settings.git_author_name,
                                  author_email=self.rt.settings.git_author_email)
            self.rt.recorder.approve_file_changes(approved_files)
            self.log(f"Committed {len(approved_files)} files as {commit_id[:10]}; pushing")
            ws.push(branch, token=self.rt.token_provider())
            pr = github.create_pull_request(
                full_name, title=f"[DevFlow AI] {title}", body=build_pr_body(state), head=branch, base=base,
                draft=self.rt.create_draft_pull_requests,
            )
        except GitHubError:
            raise
        finally:
            github.close()
        self.rt.recorder.save_pull_request({
            "repository_full_name": full_name, "number": pr["number"], "url": pr["html_url"],
            "title": pr.get("title", title), "head_branch": branch, "base_branch": base, "commit_sha": commit_id,
            "state": pr.get("state", "open"), "draft": bool(pr.get("draft")),
        })
        self.log(f"Pull request opened: {pr['html_url']}")
        return {"feature_branch": branch, "commit_id": commit_id, "pull_request_url": pr["html_url"],
                "pull_request_number": pr["number"]}
